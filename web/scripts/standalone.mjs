import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { argv } from 'node:process';
import { fileURLToPath, URL } from 'node:url';
import react from '@vitejs/plugin-react';
import { build } from 'vite';

const web = fileURLToPath(new URL('../', import.meta.url));
const output = resolve(web, '../index.html');
const require = createRequire(import.meta.url);
const requireFromReactDom = createRequire(require.resolve('react-dom/package.json'));

// Compile the same application as the Vite site for browsers opening a file URL.
const result = await build({
  root: web,
  configFile: false,
  publicDir: false,
  plugins: [react()],
  define: { 'process.env.NODE_ENV': '"production"' },
  build: {
    write: false,
    lib: { entry: resolve(web, 'src/main.tsx'), name: 'Movieverse', formats: ['iife'] },
  },
});
const [bundle] = Array.isArray(result) ? result : [result];
const script = bundle.output.find(file => file.type === 'chunk')?.code;
const stylesheet = bundle.output.find(file => file.type === 'asset' && file.fileName.endsWith('.css'))?.source;
if (bundle.output.length !== 2 || !script || typeof stylesheet !== 'string') {
  throw new Error('The standalone preview requires one script and one stylesheet.');
}
if (/<\/script/i.test(script) || /<\/style/i.test(stylesheet)) {
  throw new Error('Bundle contains an HTML closing tag and cannot be embedded safely.');
}

const files = ['manifest.v1.json', 'catalog.v1.json', 'geometry.v1.json'];
const data = await Promise.all(files.map(async file => {
  const raw = await readFile(resolve(web, '../data/sample', file), 'utf8');
  const json = JSON.stringify(JSON.parse(raw)).replaceAll('<', '\\u003c');
  return `    <script type="application/json" id="atlas-${file}">${json}</script>`;
}));

const vendors = [
  require.resolve('react/package.json'),
  require.resolve('react-dom/package.json'),
  requireFromReactDom.resolve('scheduler/package.json'),
];
const notices = await Promise.all(vendors.map(async manifest => {
  const { name } = JSON.parse(await readFile(manifest, 'utf8'));
  const license = await readFile(resolve(dirname(manifest), 'LICENSE'), 'utf8');
  return name + '\n' + license.trim().replaceAll('\r\n', '\n');
}));

const html = `<!doctype html>
<!-- Generated by pnpm build:standalone in web/. Edit the React app there. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    <meta name="theme-color" content="#0b101a" />
    <title>Movieverse | Cinema atlas</title>
    <style>${stylesheet.trim()}</style>
  </head>
  <body>
    <div id="root"></div>
    <noscript>Enable JavaScript to use the Movieverse atlas.</noscript>
${data.join('\n')}
    <script>${script.trim()}</script>
  </body>
</html>
<!-- Third-party licenses
${notices.join('\n\n')}
-->
`;

if (argv.includes('--check')) {
  const checkedIn = await readFile(output, 'utf8');
  if (checkedIn.replaceAll('\r\n', '\n') !== html) {
    throw new Error('The root index.html is out of date. Run pnpm build:standalone from web/.');
  }
} else {
  await writeFile(output, html);
}
